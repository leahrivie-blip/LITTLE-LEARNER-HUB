function renameOnPlan(plan, fromTitle, toTitle) {
  const next = JSON.parse(JSON.stringify(plan));
  for (const day of Object.keys(next.dailyPlans || {})) {
    for (const it of next.dailyPlans[day].items || []) {
      if (String(it.title || "").toLowerCase() === fromTitle.toLowerCase()) {
        it.title = toTitle;
      }
    }
  }
  return next;
}

function stripTitles(plan, titles) {
  const remove = new Set(titles.map((t) => t.toLowerCase()));
  const next = JSON.parse(JSON.stringify(plan));
  for (const day of Object.keys(next.dailyPlans || {})) {
    next.dailyPlans[day].items = (next.dailyPlans[day].items || []).filter(
      (it) => !remove.has(String(it.title || "").toLowerCase()),
    );
  }
  return next;
}

