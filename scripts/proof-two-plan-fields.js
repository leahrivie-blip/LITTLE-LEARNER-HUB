/**
 * Full plan-item + weekday rewrites for Amazing Apples + All About Me proof lessons.
 * Rewrites legacy plan fields (not enrichment-only patches) so contradictions disappear.
 */
"use strict";

function patchItem(item, patch) {
  return { ...item, ...patch };
}

function rewriteItemsByTitle(plan, byTitle) {
  const next = JSON.parse(JSON.stringify(plan));
  for (const day of Object.keys(next.dailyPlans || {})) {
    next.dailyPlans[day].items = (next.dailyPlans[day].items || []).map((it) => {
      const patch = byTitle[it.title];
      return patch ? patchItem(it, patch) : it;
    });
  }
  return next;
}

function applyDayMeta(plan, dayMeta) {
  const next = JSON.parse(JSON.stringify(plan));
  for (const [day, meta] of Object.entries(dayMeta)) {
    next.dailyPlans[day] = { ...next.dailyPlans[day], ...meta };
  }
  return next;
}

