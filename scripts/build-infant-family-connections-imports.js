function renderWeek(week) {
  const dayOrder = ["MONDAY", "TUESDAY", "WEDNESDAY", "THURSDAY", "FRIDAY"];
  return [
    "TITLE:",
    week.title,
    "",
    "AGE_GROUP:",
    "Infant 0-12 Months",
    "",
    "THEME:",
    week.theme,
    "",
    "PLAN:",
    "Pro",
    "",
    "STATUS:",
    "published",
    "",
    "LEARNING_DOMAINS:",
    LEARNING_DOMAINS,
    "",
    "WEEKLY_OVERVIEW:",
    week.overview,
    "",
    "LEARNING_OBJECTIVES:",
    lines(week.objectives),
    "",
    "WEEKLY_MATERIALS:",
    lines(week.materials),
    "",
    "VOCABULARY:",
    lines(week.vocabulary),
    "",
    "BOOKS:",
    lines(week.books),
    "",
    "SONGS:",
    lines(week.songs),
    "",
    "FAMILY_CONNECTION:",
    week.family,
    "",
    "OBSERVATION_OPPORTUNITIES:",
    week.observations,
    "",
    "ADAPTATIONS:",
    week.adaptations,
    "",
    ...dayOrder.map((day) => dayBlock(day, week.days[day])),
  ].join("\n");
}

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const week of WEEKS) {
    const outPath = path.join(OUT_DIR, week.file);
    fs.writeFileSync(outPath, `${renderWeek(week).trim()}\n`);
    console.log(`Wrote ${path.relative(process.cwd(), outPath)}`);
  }
  console.log(`Built ${WEEKS.length} Family Connections infant Pro imports.`);
}

main();
