const fs = require("fs");
const path = require("path");

const OUT_DIR = path.join(__dirname, "curriculum-infant-family-connections-imports");

const LEARNING_DOMAINS = [
  "Social Emotional",
  "Language & Literacy",
  "Physical Development",
  "Science",
  "Creative Arts",
].join(", ");

function lines(items) {
  return items.map((item) => String(item).trim()).filter(Boolean).join("\n");
}

function activityBlock({
  name,
  category,
  objective,
  description,
  materials,
  setup,
  teacherRole,
  teacherLanguage,
  directions,
  learningGoals,
  observations,
  vocabulary,
  extensions,
  adaptations,
  safetyNotes,
  ageModifications,
}) {
  return [
    "ACTIVITY_NAME:",
    name,
    "CATEGORY:",
    category,
    "OBJECTIVE:",
    objective,
    "DESCRIPTION:",
    description,
    "MATERIALS:",
    materials,
    "SETUP:",
    setup,
    "TEACHER_ROLE:",
    teacherRole,
    "TEACHER_LANGUAGE:",
    teacherLanguage,
    "DIRECTIONS:",
    directions,
    "LEARNING_GOALS:",
    learningGoals,
    "OBSERVATION_OPPORTUNITIES:",
    observations,
    "VOCABULARY:",
    vocabulary,
    "EXTENSIONS:",
    extensions,
    "ADAPTATIONS:",
    adaptations,
    "SAFETY_NOTES:",
    safetyNotes,
    "AGE_MODIFICATIONS:",
    ageModifications,
    "",
  ].join("\n");
}

function dayBlock(day, data) {
  const parts = [
    day,
    "",
    "DAILY_THEME:",
    data.theme,
    "",
    "DAILY_OBJECTIVES:",
    lines(data.objectives),
    "",
    "DAILY_VOCABULARY:",
    data.vocabulary,
    "",
    "DAILY_MATERIALS:",
    lines(data.materials),
    "",
    "DAILY_LEARNING_DOMAINS:",
    data.domains || LEARNING_DOMAINS,
    "",
    "DAILY_BOOK:",
    data.book,
    "",
    "DAILY_SONG:",
    data.song,
    "",
    "CIRCLE_TIME:",
    data.circleTime,
    "",
    "OUTDOOR_PLAY:",
    data.outdoor,
    "",
    "DAILY_OBSERVATIONS:",
    data.observations,
    "",
    "DAILY_ADAPTATIONS:",
    data.adaptations,
    "",
    "SAFETY_NOTES:",
    data.safety,
    "",
  ];
  for (const act of data.activities) {
    parts.push(activityBlock(act));
  }
  return parts.join("\n");
}

function infantDefaults(themeWord) {
  return {
    teacherRole: "Stay close, narrate gently, and follow each infant's cues.",
    teacherLanguage: `"Look. ${themeWord}. You are exploring. I see you trying. We are together."`,
    setup: "Prepare a clean floor mat and place materials within easy reach before infants arrive.",
    extensions: "Repeat the experience later in the day during a calm one-on-one moment.",
    adaptations: "Shorten the experience for younger infants and offer more movement space for older infants.",
    safetyNotes: "Use only large, washable, infant-safe materials with no small parts. Supervise closely.",
    ageModifications: "0-6 months: Short supported experiences with close positioning. 6-12 months: Encourage reaching, crawling, cruising, and more independent exploration.",
  };
}

function mkActivity(overrides) {
  const defaults = infantDefaults(overrides.themeWord || "together");
  return {
    name: overrides.name,
    category: overrides.category,
    objective: overrides.objective,
    description: overrides.description,
    materials: overrides.materials,
    setup: overrides.setup || defaults.setup,
    teacherRole: overrides.teacherRole || defaults.teacherRole,
    teacherLanguage: overrides.teacherLanguage || defaults.teacherLanguage,
    directions: overrides.directions,
    learningGoals: overrides.learningGoals,
    observations: overrides.observations,
    vocabulary: overrides.vocabulary,
    extensions: overrides.extensions || defaults.extensions,
    adaptations: overrides.adaptations || defaults.adaptations,
    safetyNotes: overrides.safetyNotes || defaults.safetyNotes,
    ageModifications: overrides.ageModifications || defaults.ageModifications,
  };
}

