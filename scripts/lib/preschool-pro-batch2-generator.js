function buildActivity(themeConfig, slotKey, template) {
  const spec = themeConfig.activities[slotKey];
  return {
    name: spec.name,
    category: template.category,
    objective: spec.objective,
    description: spec.objective,
    materials: themeConfig.materials.slice(0, 4).join("\n"),
    setup: `Prepare materials for ${spec.name}.`,
    teacherRole: "Model vocabulary, ask open questions, and support safe participation.",
    directions: [
      "Introduce the activity and materials.",
      "Demonstrate one example if helpful.",
      "Invite children to participate and explore.",
      "Ask children to describe what they notice or create.",
      "Clean up together and reflect briefly.",
    ],
    goals: [spec.objective],
    observations: ["Observe participation, engagement, and use of theme vocabulary."],
  };
}

function generateLessonPlans() {
  const dayKeys = ["monday", "tuesday", "wednesday", "thursday", "friday"];
  return THEMES.map((themeConfig) => {
    const days = {};
    dayKeys.forEach((day, dayIndex) => {
      days[day] = DAY_ACTIVITY_TEMPLATES[dayIndex].map((template) =>
        buildActivity(themeConfig, template.slot, template),
      );
    });
    return {
      title: themeConfig.title,
      theme: themeConfig.theme,
      plan: "Pro",
      status: "published",
      ageGroup: "Preschool 3-5 Years",
      learningDomains: DOMAINS,
      weeklyOverview: themeConfig.weeklyOverview,
      objectives: themeConfig.objectives,
      materials: themeConfig.materials,
      vocabulary: themeConfig.vocabulary,
      books: themeConfig.books,
      songs: themeConfig.songs,
      familyConnection: themeConfig.familyConnection,
      observationOpportunities: themeConfig.observationOpportunities,
      adaptations: themeConfig.adaptations,
      days,
    };
  });
}

module.exports = { THEMES, generateLessonPlans };
